// ─── BUILD CONTRACT DESTINATIONS GEOJSON ─────────────────────────────────────
// Builds a FeatureCollection of all routesDB destinations in unlocked regions,
// for the Mapbox 'contract-dest-dots' layer.
function buildContractDestinationsGeoJSON(unlockedRegions) {
    if (typeof italianRoutesDB === 'undefined') return { type:'FeatureCollection', features:[] };

    const availableDBRegions = new Set();
    (unlockedRegions || []).forEach(gr => {
        (REGION_TO_DB[gr] || []).forEach(dbr => availableDBRegions.add(dbr));
    });

    const seen = new Set();
    const features = [];
    italianRoutesDB.forEach(route => {
        if (!availableDBRegions.has(route.region)) return;
        // Destination dot
        const destKey = route.destination + '|' + route.region;
        if (!seen.has(destKey)) {
            seen.add(destKey);
            const coords = resolveCoords(route.destination);
            if (coords) {
                features.push({
                    type: 'Feature',
                    geometry: { type: 'Point', coordinates: coords },
                    properties: {
                        name: route.destination,
                        region: route.region,
                        type: route.type,
                        vehicle: route.vehicle,
                        price: route.sellingPrice,
                    }
                });
            }
        }
    });
    return { type: 'FeatureCollection', features };
}
window.buildContractDestinationsGeoJSON = buildContractDestinationsGeoJSON;
